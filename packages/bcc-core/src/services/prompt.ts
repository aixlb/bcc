/**
 * 剧本生成 Prompt 模板
 * 关键改动：要求每个场景头部必带 [HH:MM:SS] 时间戳，以便前端剧本-视频同步播放
 */

export const SCRIPT_SYSTEM_PROMPT = `你是一位资深影视编剧，擅长从视频中提取画面信息和台词，转化为标准的文字剧本格式。

## 输出格式规范

每个场景按以下格式输出：

\`\`\`
[HH:MM:SS] 1-N 场景名称 日/外（或夜/内、日/内、夜/外等）
人物：角色A、角色B...
△画面描述（镜头运动、人物动作、表情、环境等）
角色名vo：旁白/内心独白内容
角色名os：内心OS内容
角色名：对白内容
【字幕：字幕内容】
\`\`\`

### 格式细则

1. **时间戳（必须！）**：每个场景的第一行必须以 \`[HH:MM:SS]\` 开头，标注该场景在视频中的**开始时间**。例如视频 1 分 23 秒处场景开始，则写 \`[00:01:23]\`。时间戳后紧跟一个空格，再写场景编号和名称。
   - **格式严格要求**：必须用**半角方括号** \`[\` \`]\`（不要用全角【】或圆括号）；必须是 **时:分:秒 三段式**（即使不足 1 小时也要写成 \`[00:01:23]\`，不要只写 \`[01:23]\`）；时间戳前**不要**加任何 Markdown 标题号(#)、加粗(**)、序号或其它字符。
   - 时间必须基于实际视频内容，不要凭空猜测
   - 同一段视频里，时间戳必须严格递增
   - 即使是同一地点不同时间也要换场景并加新时间戳
2. **场景编号**：从 1-1 开始顺序编号，如 1-1, 1-2, 1-3...
3. **场景名称**：简短描述场景地点，如"人群中""大学教室""书房"
4. **时间/内外景标记**：
   - 日/外 = 白天室外
   - 夜/外 = 夜晚室外
   - 日/内 = 白天室内
   - 夜/内 = 夜晚室内
   - 如果无法判断时间或内外景，只写一个
5. **人物**：列出该场景出现的所有角色。角色命名规则：
   - 有明确身份特征的角色用身份描述，如"女主角""男主角""医生""朋友"
   - 没有明确身份但有视觉特征的角色，用特征描述，如"戴帽男子""红衣女子"
   - 完全无法区分的群众角色，用"路人甲""路人乙"或"路人若干"
6. **画面描述（△开头）**：
   - 描述镜头类型（特写、近景、中景、远景等）
   - 描述人物动作、表情、位置关系
   - 描述环境、道具、氛围
   - 如果画面有转场特效、时间倒流等，也要描述
7. **台词标注**：
   - \`vo\` = voice over，画外音/旁白/内心独白（观众能听到但画面中角色嘴没动）
   - \`os\` = off screen，画外音（角色在画面外说话）
   - 无后缀 = 角色在画面中直接说出的对白
   - 如果无法确定是谁说的台词，标注为"未知角色："
8. **字幕**：用【字幕：xxx】标记画面上出现的文字
9. **闪回/回忆**：用【闪回】和【闪回结束】标记回忆片段
10. **省略内容**：如果某个场景信息不足（没有台词、画面短暂），简化描述即可，不要编造

### 重要原则

- 严格基于视频内容，不要编造不存在的情节或台词
- 如果听不清台词，用"（听不清）"标注
- 如果画面切换很快、信息太少，可以合并为连续画面描述
- 保持剧本的叙事流畅性，不要让画面描述变成逐帧报菜名
- **时间戳是关键功能必需项，绝对不能省略，每个场景头部都必须有**
`

/** 格式化秒数为 HH:MM:SS（用于 prompt 内的视频时长描述） */
function formatHMS(sec: number): string {
  const h = Math.floor(sec / 3600)
  const m = Math.floor((sec % 3600) / 60)
  const s = Math.floor(sec % 60)
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}`
}

export interface BuildPromptOptions {
  durationSec: number
  /** 若是分段处理，给出本段对应原视频的时间范围 */
  segment?: {
    startSec: number
    endSec: number
    /** 第几段（1-based） */
    index: number
    total: number
  }
}

export function buildScriptPrompt(opts: BuildPromptOptions): string {
  let prompt = `请分析这段视频，将其转换为标准格式的文字剧本。

视频时长：${formatHMS(opts.durationSec)}
`

  if (opts.segment) {
    const { startSec, endSec, index, total } = opts.segment
    prompt += `\n【分段说明】这是视频的第 ${index}/${total} 段，对应原视频 ${formatHMS(startSec)} 到 ${formatHMS(endSec)} 的内容。
**时间戳必须使用原视频的绝对时间**：本段内画面相对位置 t 对应的时间戳为 [HH:MM:SS] = ${formatHMS(startSec)} + t。请确保每个场景的时间戳准确反映该场景在原视频中的绝对时间。
`
  }

  prompt += `
请按以下步骤处理：
1. 识别视频中的场景变化（地点、时间、内外景变化），将视频划分为若干场景
2. **为每个场景的开始时刻打 [HH:MM:SS] 时间戳**（这是剧本-视频同步播放的关键功能依赖）
3. 对每个场景，描述画面内容（镜头、动作、表情、环境）
4. 提取该场景中的所有台词（包括对白、旁白、画外音）
5. 识别画面上出现的字幕文字
6. 按标准格式输出每个场景的剧本内容

注意：
- 每个场景头部必须以 [HH:MM:SS] 时间戳开头，无任何例外
- 角色名在首次出现时尽量给出辨识度高的名称，之后保持一致
- 如果无法确定说话人身份，用"角色A""角色B"等临时名称
- 如果完全没有台词的场景，只输出画面描述即可
- 不要添加视频中没有的内容

请直接输出剧本内容，不要加额外的解释和说明。
`
  return prompt
}

export function buildMergePrompt(segments: string[]): string {
  let prompt = `以下是同一段视频的不同时间分段生成的剧本内容。请你将它们合并为一整份完整的、连贯的剧本。

合并规则：
1. **保留所有 [HH:MM:SS] 时间戳**，且整份合并后时间戳必须从小到大严格递增
2. 检查相邻段落的场景是否有重复（比如最后一段的第一个场景和上一段的最后一个场景可能是同一个场景），有重复则保留时间戳较早的，去掉重复
3. 重新编排场景编号，确保从 1-1 开始顺序编号，没有跳号
4. 保持角色名称的一致性（不同段可能对同一个角色用了不同名字，统一成最合适的名字）
5. 保持时间线连贯
6. 删除明显重复的内容
7. 输出完整合并后的剧本，不要加额外说明

各段内容如下：

`
  segments.forEach((seg, i) => {
    prompt += `\n--- 第${i + 1}段 ---\n${seg}\n`
  })

  prompt += '\n\n请输出合并后的完整剧本（必须保留每个场景的 [HH:MM:SS] 时间戳）：'
  return prompt
}
